import { Prisma } from "@prisma/client";

/**
 * Which unique constraint did a Prisma error come from?
 *
 * A P2002 only says "some unique index rejected this write". Several indexes can be involved
 * in one request (a new order has a unique orderNumber AND its units have unique serials), so
 * treating every P2002 as "serial number taken" gives the wrong message. Prisma reports the
 * columns in `meta.target`; verified against this project's Postgres (including the partial
 * unique index on Complaint.unitId): `{ modelName: "RecdUnit", target: ["serialNo"] }`.
 */
export function uniqueViolationTarget(err: unknown): { model: string | null; fields: string[] } | null {
  if (!(err instanceof Prisma.PrismaClientKnownRequestError) || err.code !== "P2002") return null;
  const meta = (err.meta ?? {}) as { modelName?: unknown; target?: unknown };
  const target = meta.target;
  const fields = Array.isArray(target) ? target.map(String) : typeof target === "string" ? [target] : [];
  return { model: typeof meta.modelName === "string" ? meta.modelName : null, fields };
}

/** True only when the error is a unique violation on exactly this model/column. */
export function isViolationOn(err: unknown, model: string, field: string): boolean {
  const t = uniqueViolationTarget(err);
  if (!t) return false;
  if (t.model !== null && t.model !== model) return false;
  // Array form is ["col"]; some drivers report the index name as a string, which contains the column.
  return t.fields.some((f) => f === field || f.includes(field));
}

/** RecdUnit.serialNo is already registered. */
export const isSerialConflict = (err: unknown) => isViolationOn(err, "RecdUnit", "serialNo");

/** Order.orderNumber (generated by the server) is already in use. */
export const isOrderNumberConflict = (err: unknown) => isViolationOn(err, "Order", "orderNumber");

/**
 * User.phone (unique) is already used by another user/contact. A contact created INSIDE a customer
 * (nested create) is reported by Prisma against the parent model - `{ modelName: "Customer", target: ["phone"] }`
 * (verified against this project's Postgres) - so both models are accepted; Customer has no phone column of its own.
 */
export const isUserPhoneConflict = (err: unknown) => isViolationOn(err, "User", "phone") || isViolationOn(err, "Customer", "phone");

/**
 * User.email (unique) is already used by another user. Like the phone, a contact created inside a customer
 * (nested create) can be reported against the parent model, so both models are accepted.
 */
export const isUserEmailConflict = (err: unknown) => isViolationOn(err, "User", "email") || isViolationOn(err, "Customer", "email");

/** Complaint.ticketNumber (generated by the server) is already in use. */
export const isTicketNumberConflict = (err: unknown) => isViolationOn(err, "Complaint", "ticketNumber");

/** The partial unique index allowing only one open Complaint per RECD unit. */
export const isOpenComplaintConflict = (err: unknown) => isViolationOn(err, "Complaint", "unitId");

export const SERIAL_RACE_MESSAGE = "One of those serial numbers was just registered by someone else";

export function orderNumberConflictMessage(orderNumber: string): string {
  return `Order number ${orderNumber} was generated at the same moment as another order. Nothing was saved - please submit again.`;
}
